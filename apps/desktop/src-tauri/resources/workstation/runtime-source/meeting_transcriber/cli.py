from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

from dotenv import load_dotenv

from .formatting import (
    render_comparison_html,
    render_srt,
    render_transcript,
    safe_slug,
    transcript_lines,
    write_json,
)
from .summarization import (
    ModelResult,
    render_metrics_markdown,
    summarize_with_model,
)
from .transcription import transcribe_recording


PROJECT_ROOT = Path(__file__).resolve().parent.parent


def _optional_positive_int(value: str) -> int:
    integer = int(value)
    if integer <= 0:
        raise argparse.ArgumentTypeError("must be greater than zero")
    return integer


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Transcribe a meeting once, optionally identify speakers, and compare "
            "minutes generated by multiple local LLMs."
        )
    )
    parser.add_argument("input", type=Path, help="Audio/video file, or a prior transcript.json")
    parser.add_argument("-o", "--output", type=Path, help="Output directory")
    parser.add_argument("--whisper-model", default="large-v3")
    parser.add_argument("--language", help="ISO language code, e.g. en or ru (default: auto)")
    parser.add_argument("--device", default="cuda", choices=["cuda", "cpu"])
    parser.add_argument("--compute-type", default="float16")
    parser.add_argument("--batch-size", type=_optional_positive_int, default=8)
    parser.add_argument("--no-align", action="store_true")
    parser.add_argument("--no-diarize", action="store_true")
    parser.add_argument("--min-speakers", type=_optional_positive_int)
    parser.add_argument("--max-speakers", type=_optional_positive_int)
    parser.add_argument("--no-summary", action="store_true")
    parser.add_argument(
        "--provider",
        default=os.getenv("LLM_PROVIDER", "ollama"),
        choices=["ollama", "openai", "vllm", "deepseek"],
    )
    parser.add_argument(
        "--base-url",
        default=os.getenv("LLM_BASE_URL", "http://127.0.0.1:11434"),
    )
    parser.add_argument(
        "--models",
        default=os.getenv("LLM_MODELS", "gemma4:e4b,gemma4:26b"),
        help="Comma-separated local model names",
    )
    parser.add_argument(
        "--summary-language",
        default="the same language as the transcript",
        help='For example "English", "Russian", or the default auto behavior',
    )
    parser.add_argument("--chunk-chars", type=_optional_positive_int, default=16_000)
    return parser


def _default_output(input_path: Path) -> Path:
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    return PROJECT_ROOT / "outputs" / f"{input_path.stem}-{stamp}"


def _load_existing_transcript(path: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(payload, dict) and "transcript" in payload:
        transcript = payload["transcript"]
        metadata = payload.get("metadata", {})
    else:
        transcript = payload
        metadata = {}
    if not isinstance(transcript, dict) or not isinstance(transcript.get("segments"), list):
        raise ValueError("JSON input must contain transcript.segments or top-level segments")
    metadata = dict(metadata)
    metadata["reused_transcript"] = str(path)
    return transcript, metadata


def _write_transcription_outputs(
    output_dir: Path,
    transcript: dict[str, Any],
    metadata: dict[str, Any],
    source_name: str,
) -> None:
    segments = transcript.get("segments", [])
    language = transcript.get("language") or metadata.get("language")
    write_json(
        output_dir / "transcript.json",
        {"metadata": metadata, "transcript": transcript},
    )
    (output_dir / "transcript.md").write_text(
        render_transcript(segments, source_name=source_name, language=language),
        encoding="utf-8",
    )
    (output_dir / "transcript.srt").write_text(
        render_srt(segments),
        encoding="utf-8",
    )


def _run_summaries(
    output_dir: Path,
    transcript: dict[str, Any],
    *,
    provider: str,
    base_url: str,
    models: list[str],
    api_key: str | None,
    summary_language: str,
    chunk_chars: int,
) -> list[ModelResult]:
    lines = transcript_lines(transcript.get("segments", []))
    if not lines:
        raise ValueError("Transcript contains no text segments")
    results: list[ModelResult] = []
    for index, model in enumerate(models, start=1):
        print(f"[summary {index}/{len(models)}] Running {model!r} via {provider}...")
        result = summarize_with_model(
            lines,
            provider=provider,
            base_url=base_url,
            model=model,
            api_key=api_key,
            summary_language=summary_language,
            chunk_chars=chunk_chars,
        )
        slug = safe_slug(model)
        (output_dir / f"minutes-{slug}.md").write_text(
            result.summary_markdown,
            encoding="utf-8",
        )
        write_json(output_dir / f"extraction-{slug}.json", result.extraction)
        write_json(output_dir / f"metrics-{slug}.json", result.metrics)
        results.append(result)
    return results


def _write_comparison(output_dir: Path, results: list[ModelResult]) -> None:
    metrics = render_metrics_markdown(results)
    (output_dir / "comparison.md").write_text(
        "# Summary comparison\n\n"
        + metrics
        + "\n## Files\n\n"
        + "\n".join(
            f"- `{result.model}`: `minutes-{safe_slug(result.model)}.md`"
            for result in results
        )
        + "\n",
        encoding="utf-8",
    )
    write_json(
        output_dir / "comparison.json",
        {"models": [result.metrics for result in results]},
    )
    if len(results) >= 2:
        (output_dir / "compare.html").write_text(
            render_comparison_html(
                [
                    (result.provider, result.model, result.summary_markdown)
                    for result in results
                ],
                metrics,
            ),
            encoding="utf-8",
        )


def main(argv: list[str] | None = None) -> int:
    load_dotenv(PROJECT_ROOT / ".env")
    parser = build_parser()
    args = parser.parse_args(argv)
    input_path = args.input.expanduser().resolve()
    if not input_path.is_file():
        parser.error(f"input file does not exist: {input_path}")
    if args.min_speakers and args.max_speakers and args.min_speakers > args.max_speakers:
        parser.error("--min-speakers cannot exceed --max-speakers")

    output_dir = (args.output or _default_output(input_path)).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    source_name = input_path.name

    try:
        if input_path.suffix.lower() == ".json":
            print(f"Reusing transcript: {input_path}")
            transcript, metadata = _load_existing_transcript(input_path)
        else:
            transcript, metadata = transcribe_recording(
                input_path,
                model_name=args.whisper_model,
                language=args.language,
                device=args.device,
                compute_type=args.compute_type,
                batch_size=args.batch_size,
                align=not args.no_align,
                diarize=not args.no_diarize,
                hf_token=os.getenv("HF_TOKEN") or os.getenv("HUGGINGFACE_TOKEN"),
                min_speakers=args.min_speakers,
                max_speakers=args.max_speakers,
            )
        metadata["pipeline"] = {
            "python": sys.version,
            "platform": platform.platform(),
            "ffmpeg": shutil.which("ffmpeg"),
        }
        _write_transcription_outputs(output_dir, transcript, metadata, source_name)
        print(f"Transcript written to {output_dir}")

        if not args.no_summary:
            models = [value.strip() for value in args.models.split(",") if value.strip()]
            if not models:
                raise ValueError("At least one model is required unless --no-summary is used")
            results = _run_summaries(
                output_dir,
                transcript,
                provider=args.provider,
                base_url=args.base_url,
                models=models,
                api_key=os.getenv("LLM_API_KEY"),
                summary_language=args.summary_language,
                chunk_chars=args.chunk_chars,
            )
            _write_comparison(output_dir, results)
            print(f"Comparison written to {output_dir / 'comparison.md'}")

        print(f"Done: {output_dir}")
        return 0
    except KeyboardInterrupt:
        print("\nCancelled.", file=sys.stderr)
        return 130
    except Exception as exc:
        print(f"\nERROR: {exc}", file=sys.stderr)
        print(f"Partial outputs, if any, are in: {output_dir}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
